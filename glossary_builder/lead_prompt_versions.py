# V6 — strictest disambiguation (currently active definition)
# =========================================================================
# Same as v5 plus the strict disambiguation between buyer-possession
# 'у кого есть' and networking 'кто работает с', plus stronger seller-
# catalog detection ('[method/geo] есть :)' form), plus personal-FX
# rejection. Highest measured precision but over-suppresses some real
# 'у кого есть' leads.
V6_LEAD_DEFINITION = V5_LEAD_DEFINITION + (
    "\n"
    "  CRITICAL DISAMBIGUATION: 'у кого есть X' (the speaker WANTS the\n"
    "  thing — LEAD) is structurally different from 'кто работает с X'\n"
    "  or 'кто использует X' (the speaker wants to FIND PEOPLE — NOT a\n"
    "  lead). Treat these differently.\n"
    "  - One-off personal transactions: 'Нужно провести транзакцию через\n"
    "    X, оплатить отель / визу / билеты' — individual consumer use,\n"
    "    not merchant payment-service procurement."
)

