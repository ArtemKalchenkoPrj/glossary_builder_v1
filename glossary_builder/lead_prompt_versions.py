"""Frozen versions of the lead-extractor's ``lead_definition`` prompt.

The lead extractor's behaviour is steered almost entirely by the
``lead_definition`` string in ``LeadExtractionConfig``. As we iterated
through v1..v6 we kept editing this string in-place, so the current
codebase only carries the latest version.

To compare prompt versions on the same corpus we need them as immutable
named constants. The reconstructions below preserve the *intent* of each
audited version. Behaviour will be very close but not bit-identical to
the original runs — the surrounding system prompt and rules are still the
common ones (those didn't change across v3..v6).

Naming:
    V3 — high precision, conservative recovery. 92.5% precision in audit.
    V5 — best balance. 85% precision, 91% suppression accuracy.
    V6 — strict disambiguation of "у кого есть" vs "кто работает с".
         92.5% precision but kills real "у кого есть" leads.

The active default is V5 because the auditor recommended it as the
balanced choice.
"""

from __future__ import annotations


# Shared scaffolding used by every version below.
_COMMON_INTRO = (
    "A LEAD is a message from a BUYER in the high-risk payments "
    "ecosystem — an iGaming/casino operator, affiliate, merchant, or "
    "platform — who is actively shopping for a payment service (PSP, "
    "acquirer, payment method, gateway, orchestrator, KYC provider, "
    "etc.) AND signals a concrete need.\n"
    "\n"
)


