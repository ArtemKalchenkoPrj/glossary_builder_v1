"""Merchant vs Aggregator classifier (Haiku gate).

Classifies REAL_LEAD verdicts into:
  - direct_merchant: end-client seeking payment processing
  - aggregator: intermediary seeking providers/merchants/traffic

Runs AFTER the main buyer judge and BEFORE DB write.
Does NOT change is_lead or verdict — only writes to is_merchant column.
"""
from __future__ import annotations

import logging
import os
from dataclasses import dataclass

from glossary_builder.llm import LLMClient, LLMError
from glossary_builder.config import LLMConfig

logger = logging.getLogger(__name__)

_MERCHANT_GATE_SYSTEM = """\
Ты классификатор сообщений из Telegram-чатов iGaming/high-risk индустрии.

Задача: определить, кто автор — ПРЯМОЙ МЕРЧАНТ или АГРЕГАТОР/ПОСРЕДНИК.
Все сообщения уже проверены как запросы на платёжную инфраструктуру (REAL_LEAD). Тебе нужно только разделить их на две категории.

ПРАВИЛО ПО УМОЛЧАНИЮ: если нет явных маркеров агрегатора — это direct_merchant. ~85% сообщений в этом потоке — прямые мерчанты.

═══ ПРИОРИТЕТ ИСТОЧНИКОВ (ВАЖНО) ═══

Если в сообщении ниже есть доп. контекст (био автора, статистика чата) — он ВСПОМОГАТЕЛЬНЫЙ. ТЕКСТ САМОГО СООБЩЕНИЯ ВСЕГДА ПРИОРИТЕТНЕЕ:
- Статистика чата показывает исторический состав сигналов в этой группе — это приор по умолчанию, когда сообщение само по себе неинформативно, НЕ инструкция переклассифицировать конкретное сообщение под большинство. Если текст содержит прямой маркер («в поиске провайдеров», «ищу приёмку» и т.п.) — используй маркер из текста, а не долю сигналов в чате.
- Био автора (каналы, ники, подписи) может намекать на роль, но если оно противоречит прямому смыслу сообщения — доверяй сообщению.
- Если контекста нет совсем — классифицируй по тексту.

═══ DIRECT_MERCHANT (по умолчанию) ═══
Любой, кто ИЩЕТ/ПОКУПАЕТ платёжную инфраструктуру для своего бизнеса:
- «ищу/нужен PSP/приёмку/эквайринг/метод на [гео]»
- «в поиске провайдеров» + методы/гео/чеки/ставки
- «мы прямой мерчант», «looking for payment solution»
- Короткие запросы: «кто работает с [гео/метод]?», «Send offers», «пишите в ЛС»
- Поле вида «Источник: [метод/платформа]» (например «Источник: ЮMoney», «Источник: Ozon») — это автор указывает СВОЙ входящий поток, через который к нему приходит трафик. Это маркер мерчанта, не провайдера.
- Список фич/плюшек (✅ быстрое подключение, ✅ стабильная работа, ✅ 24/7 и т.п.) РЯДОМ с «в поиске провайдеров» / «нужны связки под объём» — это стимулы, которые мерчант перечисляет, ЧТОБЫ ПРИВЛЕЧЬ провайдера к сотрудничеству. Сам по себе список плюшек НЕ делает автора агрегатором — агрегатором его делает только набор клиентов/раздача потока (см. ниже).

ЧАСТЫЕ ЛОЖНЫЕ СРАБАТЫВАНИЯ — ЭТО ВСЁ DIRECT_MERCHANT:
- «We have high traffic, looking for payment solution» — мерчант описывает свой объём
- «есть трафик, ищу приёмку/метод» — мерчант с трафиком ищет процессинг
- «ищем провайдеров, нужны стабильные связки под объём» — покупает процессинг
- «looking for P2P/P2C solution for [гео], high traffic, DM me» — покупатель
- «мы мерчи (конечники), готовы дать трафик» — прямой мерчант, даёт СВОЙ трафик
- «ищем провайдеров в каскад» БЕЗ «отдам/дадим» — покупает процессинг
- «I need PSP wires in EU, send offers» — покупатель
- «HIGH-VOLUME GATEWAY NEEDED» — покупатель
- «[Гео] с [метод]. В поиске провайдеров. Направление: [X]. Источник: [метод]. Нужны стабильные связки под объём. ✅ Быстрое подключение ✅ Стабильная работа» — шаблонное объявление мерчанта; заголовок-«шапка» — оформление, не самопрезентация провайдера
- «для обработки трафика» / «ищем провайдеров/команды для обработки трафика» — мерчант ищет процессинг для СВОЕГО трафика. Это покупка, не раздача. Aggregator только если рядом «отдам/дадим»
- «АКТУАЛЬНЫЕ УСЛОВИЯ ДЛЯ ПРОВАЙДЕРОВ» + список методов/ставок — рекламная шапка мерчанта для привлечения провайдеров, а не rate card провайдера
- Слова «агент», «агрегатор», «площадка» в самоописании НЕ меняют класс. Если автор ищет провайдера/решение/приёмку ПОД СВОЙ продукт — это direct_merchant, даже если он называет себя «агентом» или «гемблинг агрегатором». Aggregator определяется по ДЕЙСТВИЮ (раздаёт/набирает), а не по самоназванию

Слова «трафик», «объём», «volume», «high traffic» НЕ делают автора агрегатором.
Мерчант описывает свой объём чтобы привлечь провайдера — это СПРОС, не предложение.

═══ AGGREGATOR (только при ЯВНЫХ маркерах ПРОДАЖИ/РАЗДАЧИ) ═══
Aggregator = автор ПРОДАЁТ услуги, НАБИРАЕТ клиентов или РАЗДАЁТ поток:
- «ищем мерчей/мерчантов» — набирает КЛИЕНТОВ (ищет мерчей, не провайдеров!)
- «ищем мерчей(трафик)» — набирает мерчантов как источники объёма
- «ОТДАМ [ХЧ/трафик]» + ищем провайдеров — раздаёт ЧУЖОЙ поток
- «дадим объём/трафик» БЕЗ контекста покупки процессинга — раздаёт
- «набираем PSP в каскад», «отправляйте список решений»
- «примем ваш трафик», «готовы принимать ваш трафик»
- «готовы рассмотреть оферы от площадок и мерчей» — принимает заявки
- «кому нужны выплаты» — предлагает свои выплаты
- Одновременно ПРЕДОСТАВЛЯЕТ одни методы и ИЩЕТ другие (а не просто перечисляет свои плюшки)
- ДВУБЛОЧНАЯ СТРУКТУРА: блок «ищет провайдеров [список методов]» + ОТДЕЛЬНЫЙ блок «ищем трафик: [список гео]» = aggregator. Второй блок означает набор ЧУЖОГО трафика
- ДВУСТОРОННИЙ БРОКЕР: «в поисках провайдеров [список]» + отдельная секция «Мерчанты: [список гео]» = aggregator. Набирает И провайдеров И мерчантов = посредник

═══ ПРИМЕРЫ ═══
direct_merchant: «We have few forex brands, looking for payment solution in India, Thailand. High traffic. DM me»
direct_merchant: «Есть куча траффика на рубли! Ищу приемки нспк / трейдеров»
direct_merchant: «В поиске провайдеров. Нужны стабильные провайдеры под объём. БТ без чека»
direct_merchant: «Мы мерчи (конечники). Готовы дать трафик по рф. Ищем решение»
direct_merchant: «I need good PSP wires in EU - UK AT DE. Send offers»
direct_merchant: «Ищем провайдеров на МК Таджикистан/Киргизия»
direct_merchant: «Провайдеры Трансгран Таджикистан с ЮMoney. В поиске провайдеров. Направление: трансгран. Источник: ЮMoney. Нужны стабильные связки под объём. ✅ Быстрое подключение ✅ Стабильная работа»
direct_merchant: «Наша площадка находится в поиске провайдеров для обработки трафика по методам: BT PDF - 10%, Классика - 15%» — ищет провайдеров ПОД СВОЙ трафик
direct_merchant: «Рассматриваем ставки для гемблинг агрегатора. Нужна выдача по чекам от 10к» — слово «агрегатор» описывает ИХ бизнес, а действие — покупка провайдера
aggregator: «Ищем мерчей(трафик). Ищем мерчантов по таким методам»
aggregator: «Набираем PSP в каскад, отправляйте список решений»
aggregator: «Дадим объем на БТ. Ищем решения по НСПК»
aggregator: «ОТДАМ БТ С ПДФ ПОД ФО. В поиске провайдеров на метод BT+PDF»
aggregator: «Площадки и агрегаторы, у кого есть выдача — дадим объем»
aggregator: «ищет провайдеров [методы]. Так ищем трафик: [список гео]» — двублочная структура: первый блок методы, второй набор чужого трафика
aggregator: «В поисках провайдеров по [методы]. Мерчанты: [список гео]» — набирает И провайдеров И мерчантов

═══ КЛЮЧЕВОЕ ОТЛИЧИЕ (ПРИМЕНЯЙ ЭТО ПРАВИЛО ПОСЛЕДНИМ, ПЕРЕД ОТВЕТОМ) ═══
- «есть трафик, ИЩЕМ провайдеров/приёмку» → direct_merchant (ищет процессинг)
- «ОТДАМ трафик, ищем провайдеров» → aggregator (раздаёт чужой поток)
- «ищем ПРОВАЙДЕРОВ» (в любом оформлении — с плюшками, с полем «Источник», в каскад) → direct_merchant (покупает процессинг для СЕБЯ), если нет явного «отдам/дадим/наберём мерчей/ищем трафик»
- «ищем МЕРЧЕЙ/МЕРЧАНТОВ» → aggregator (набирает клиентов)
- Статистика чата и био автора — вспомогательные, не отменяют эти правила

ВАЖНО: отвечай ТОЛЬКО direct_merchant или aggregator. Варианта unknown НЕТ. Если не уверен — ставь direct_merchant.

Отвечай СТРОГО одним словом: direct_merchant или aggregator\
"""


@dataclass
class MerchantGateConfig:
    model: str = "anthropic/claude-haiku-4.5"
    max_tokens: int = 20
    temperature: float = 0.0


def classify_merchant(
    text: str,
    username: str = "",
    group_context_block: str = "",
    bio_block: str = "",
    config: MerchantGateConfig | None = None,
    llm: LLMClient | None = None,
) -> tuple[str, str]:
    """Classify a REAL_LEAD message as direct_merchant or aggregator.

    Returns:
        (label, rationale) — rationale is always empty in production (no rationale mode).
    """
    cfg = config or MerchantGateConfig()

    if llm is None:
        llm_cfg = LLMConfig(
            model=cfg.model,
            max_tokens=cfg.max_tokens,
            temperature=cfg.temperature,
        )
        llm = LLMClient(llm_cfg)

    system = _MERCHANT_GATE_SYSTEM

    user_parts = []
    if group_context_block:
        user_parts.append(group_context_block)
    if bio_block:
        user_parts.append(bio_block)
    if username:
        user_parts.append(f"Username: {username}")
    user_parts.append(f"Сообщение:\n{text}")

    user_msg = "\n\n".join(user_parts)

    try:
        resp = llm.complete(system=system, user=user_msg)
        raw = resp.text.strip()

        candidate = raw.lower().replace(".", "").replace(",", "").strip()
        if candidate in ("direct_merchant", "aggregator"):
            return candidate, ""
        logger.warning(
            "merchant_gate: unexpected response %r — defaulting to direct_merchant", raw
        )
        return "direct_merchant", ""

    except LLMError as exc:
        logger.error("merchant_gate: LLM error: %s — defaulting to direct_merchant", exc)
        return "direct_merchant", ""
